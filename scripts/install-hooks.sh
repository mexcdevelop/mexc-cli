#!/usr/bin/env bash
# install-hooks — install a local git pre-commit hook (recommended)
#
# This hook runs check-boundary plus check-exposure, check-english (staged) and
# check-test-isolation, gofmt / build / vet / test, and golangci-lint before each
# commit. CI (.github/workflows/ci.yml) runs the same gates on every pull
# request; the hook only makes a failure show up before the commit exists.
# Skip a single run with `git commit --no-verify`.
#
# golangci-lint is here because AGENTS.md §6 asks for it and nothing else ran it:
# 26 findings had accumulated by the time anyone looked. A gate no machine
# executes is a gate that decays.
#
# Usage (from the repo root): bash scripts/install-hooks.sh
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HOOK="$REPO_ROOT/.git/hooks/pre-commit"
SELF="$REPO_ROOT/scripts/install-hooks.sh"

# sha256_of prints a file's digest, or nothing when no digest tool is available.
# macOS ships shasum, most Linux images ship sha256sum; a machine with neither
# simply gets no staleness check rather than a broken hook.
sha256_of() {
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  elif command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  fi
}

# The installed hook is a COPY of what this script writes, not a link to it, so
# fixing the script does not fix anyone's hook. That gap was silent: the
# vendor-aware gofmt step landed here and every developer who had installed
# earlier kept the old one, which fails on vendored files. Stamping this script's
# digest into the hook lets the hook notice it was generated by an older version
# and say so.
SELF_SHA="$(sha256_of "$SELF")"

# Back up any pre-existing hook we didn't write, so a husky / pre-commit-framework
# / company-standard hook isn't silently destroyed. Ours carries a known marker
# line; anything without it is foreign and gets moved aside first.
if [ -e "$HOOK" ] && ! grep -q "Auto-installed by scripts/install-hooks.sh" "$HOOK"; then
  BACKUP="$HOOK.bak"
  mv "$HOOK" "$BACKUP"
  echo "! existing pre-commit hook backed up -> $BACKUP" >&2
fi

{
# The header is printf'd rather than part of the heredoc below because that
# heredoc is quoted — nothing in it expands — which is what keeps the hook body a
# verbatim copy. The digest is the one value that must be interpolated.
printf '#!/usr/bin/env bash\n'
printf '# Auto-installed by scripts/install-hooks.sh — boundary + Go quality gate.\n'
printf 'HOOK_SOURCE_SHA=%s\n' "$SELF_SHA"
cat <<'HOOK_EOF'
set -euo pipefail
ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

# Warn when this hook was generated by an older scripts/install-hooks.sh. The
# hook is a copy, so a fix to the script reaches nobody until they re-run it, and
# nothing else would ever tell them. Warn rather than block: a stale hook still
# runs real checks, and refusing the commit would punish the wrong thing.
if [ -n "${HOOK_SOURCE_SHA:-}" ]; then
  if command -v shasum >/dev/null 2>&1; then
    now="$(shasum -a 256 scripts/install-hooks.sh 2>/dev/null | cut -d' ' -f1)"
  elif command -v sha256sum >/dev/null 2>&1; then
    now="$(sha256sum scripts/install-hooks.sh 2>/dev/null | cut -d' ' -f1)"
  else
    now=""
  fi
  if [ -n "$now" ] && [ "$now" != "$HOOK_SOURCE_SHA" ]; then
    echo "pre-commit: this hook was generated from an older scripts/install-hooks.sh" >&2
    echo "            re-run to pick up the current checks: bash scripts/install-hooks.sh" >&2
  fi
fi

# Find an interpreter that RUNS, not merely a name that resolves.
#
# `command -v python3` is the wrong question on Windows. The official installer
# ships python.exe and pythonw.exe and NO python3.exe, so that name resolves to
# the Microsoft Store's App Execution Alias — a stub that exits 49 and prints
# nothing at all. The guard therefore passed, the first check "ran", `set -e`
# aborted, and the commit was refused with an exit code, no output, and no rule
# named. A gate that blocks every commit from a machine while naming nothing to
# fix is worse than one that is honestly absent, which is what the else branch
# below is for.
#
# So each candidate is probed by EXECUTING it. `py -3` is the Windows launcher,
# which is how a Python installed there is normally reached.
PYTHON=""
for candidate in python3 python; do
  if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c '' >/dev/null 2>&1; then
    PYTHON="$candidate"
    break
  fi
done
if [ -z "$PYTHON" ] && command -v py >/dev/null 2>&1 && py -3 -c '' >/dev/null 2>&1; then
  PYTHON="py -3"
fi
# Last resort: the official per-user install directory, which the Windows
# installer's default ("for me only") uses and does NOT add to PATH unless the
# "Add python.exe to PATH" box was ticked. Measured: a machine with Python 3.13
# installed there where python3, python and py all fail, so these four checks
# silently never ran. First working interpreter wins — none of these scripts
# import anything outside the standard library. A path with a space is skipped,
# because $PYTHON is expanded unquoted below to split "py -3".
if [ -z "$PYTHON" ] && [ -n "${LOCALAPPDATA:-}" ]; then
  pybase="$(cygpath -u "$LOCALAPPDATA" 2>/dev/null || echo "$LOCALAPPDATA")"
  for candidate in "$pybase"/Programs/Python/Python3*; do
    [ -d "$candidate" ] || continue
    case "$candidate" in *" "*) continue ;; esac
    if [ -x "$candidate/python.exe" ] && "$candidate/python.exe" -c '' >/dev/null 2>&1; then
      PYTHON="$candidate/python.exe"
      break
    fi
  done
fi

if [ -n "$PYTHON" ]; then
  # Unquoted on purpose: "py -3" is a command AND its argument, and the word
  # splitting is what separates them. Quoting this looks tidier and breaks it.
  # shellcheck disable=SC2086
  $PYTHON scripts/check-boundary.py
  # Disclosure gate: blocks on what a published tree must not say about the
  # service behind it. Advisory notes are printed and do not fail.
  # shellcheck disable=SC2086
  $PYTHON scripts/check-exposure.py
  # English-only gate: check the Go lines this commit STAGES against HEAD.
  # --staged uses `git diff --cached`, so unstaged edits don't false-trip it
  # and only what will actually be committed is checked.
  # shellcheck disable=SC2086
  $PYTHON scripts/check-english.py --base HEAD --staged
  # Test isolation: a test that redirects only HOME isolates nothing on Windows,
  # where os.UserHomeDir reads USERPROFILE — it would run against the developer's
  # real state directory. Invisible on the platform this is developed on.
  # shellcheck disable=SC2086
  $PYTHON scripts/check-test-isolation.py
else
  echo "pre-commit: no working python3 found, skipping check-boundary/check-exposure/check-english/check-test-isolation" >&2
  echo "            (on Windows python3/python may be a 0-byte Microsoft Store alias, not an interpreter." >&2
  echo "             %LOCALAPPDATA%\\Programs\\Python\\Python3*\\python.exe is probed too, so if this still" >&2
  echo "             says nothing was found, either install Python or turn the alias off:" >&2
  echo "             Settings > Apps > Advanced app settings > App execution aliases)" >&2
fi

if command -v go >/dev/null 2>&1; then
  # gofmt walks the filesystem, so unlike `go build ./...` it does NOT skip
  # vendor/. Third-party source is not ours to format — and `go mod vendor`
  # would undo it — so ask git for the files we author instead.
  #
  # The emptiness guard is not decoration: `gofmt -l` with no file arguments
  # reads STDIN, so piping an empty list into a bare xargs would hang the commit.
  # (`xargs -r` avoids that but is a GNU extension not every macOS ships.)
  go_files=$(git ls-files '*.go' ':(exclude)vendor/')
  unformatted=""
  if [ -n "$go_files" ]; then
    unformatted=$(printf '%s\n' "$go_files" | xargs gofmt -l)
  fi
  if [ -n "$unformatted" ]; then
    echo "pre-commit: unformatted Go files (run gofmt -w .):" >&2
    echo "$unformatted" >&2
    exit 1
  fi
  go build ./...
  go vet ./...
  go test -count=1 ./...
else
  echo "pre-commit: go not found, skipping gofmt/build/vet/test" >&2
fi

# golangci-lint runs analyzers `go vet` does not (the six reflect.Ptr findings
# were invisible to vet), so it is a separate step rather than a stricter vet.
#
# The version is pinned because the linter set is not stable across releases:
# an upgrade can introduce checks that turn a clean tree red for reasons the
# author did not write. A mismatch warns and still runs — being on the wrong
# version is worth knowing, not worth blocking a commit over.
if command -v golangci-lint >/dev/null 2>&1; then
  want="$(cat .golangci-version 2>/dev/null || true)"
  have="$(golangci-lint version 2>/dev/null | sed -n 's/.*has version \([0-9.]*\).*/\1/p')"
  if [ -n "$want" ] && [ -n "$have" ] && [ "$want" != "$have" ]; then
    echo "pre-commit: golangci-lint $have, pinned $want (see .golangci-version)" >&2
  fi
  golangci-lint run ./...
else
  echo "pre-commit: golangci-lint not found, skipping (see AGENTS.md section 6)" >&2
fi
HOOK_EOF
} > "$HOOK"

chmod +x "$HOOK"
echo "✓ installed pre-commit hook -> $HOOK"
echo "  skip a single check with: git commit --no-verify"
